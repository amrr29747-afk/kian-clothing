// Translation helper:  const t = makeT('ar');  t('cartTitle');  t('serverErr', { status: 500 })
export const makeT = (lang) => (key, vars) => {
  let s = T[lang]?.[key] ?? T.en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, vars[k]);
  return s;
};

